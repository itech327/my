#!/usr/bin/env python3
"""Generate tokens.css and tailwind.tokens.js from tokens.json.

    python3 replica/design/build_tokens.py

Run it after every token change, including the rebrand. Keys starting with
"_" are notes and are skipped.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def clean(d):
    return {k: v for k, v in d.items() if not k.startswith("_")}


def main():
    t = json.load(open(os.path.join(HERE, "tokens.json"), encoding="utf-8"))
    color, typ = clean(t["color"]), clean(t["type"])
    radius, shadow, motion = clean(t["radius"]), clean(t["shadow"]), clean(t["motion"])
    layout = clean(t["layout"])
    font = clean(t["font"])
    size = clean(t.get("size", {}))

    css = ["/* Generated by build_tokens.py from tokens.json. Do not edit by hand. */", ":root {"]
    css += [f"  --color-{k}: {v};" for k, v in color.items()]
    css += [f"  --font-{k}: {v};" for k, v in font.items()]
    for k, v in typ.items():
        css += [f"  --text-{k}: {v['size']}px;", f"  --leading-{k}: {v['line']}px;",
                f"  --weight-{k}: {v['weight']};"]
    css += [f"  --space-{i}: {v}px;" for i, v in enumerate(t["space"])]
    css += [f"  --radius-{k}: {v}px;" for k, v in radius.items()]
    css += [f"  --shadow-{k}: {v};" for k, v in shadow.items()]
    css += [f"  --motion-{k}: {v};" for k, v in motion.items()]
    css += [f"  --layout-{k}: {v}px;" for k, v in layout.items() if isinstance(v, (int, float))]
    css += [f"  --size-{k}: {v}px;" for k, v in size.items()]
    css += ["}", "",
            "html { direction: rtl; }",
            "body {",
            "  margin: 0; background: var(--color-bg); color: var(--color-text);",
            "  font-family: var(--font-sans); font-size: var(--text-base);",
            "  line-height: var(--leading-base);",
            "}",
            ":focus-visible { outline: 2px solid var(--color-focus); outline-offset: 2px; }",
            "@media (prefers-reduced-motion: reduce) {",
            "  *, *::before, *::after { transition-duration: 0ms !important; animation-duration: 0ms !important; }",
            "}", ""]
    open(os.path.join(HERE, "tokens.css"), "w", encoding="utf-8").write("\n".join(css))

    tw = {
        "colors": {k: f"var(--color-{k})" for k in color},
        "fontFamily": {k: f"var(--font-{k})" for k in font},
        "fontSize": {k: [f"var(--text-{k})", {"lineHeight": f"var(--leading-{k})",
                                              "fontWeight": f"var(--weight-{k})"}] for k in typ},
        "spacing": {**{str(v): f"{v}px" for v in t["space"]}, **{k: f"var(--size-{k})" for k in size}},
        "borderRadius": {k: f"var(--radius-{k})" for k in radius},
        "boxShadow": {k: f"var(--shadow-{k})" for k in shadow},
        "maxWidth": {"content": "var(--layout-content-max)", "prose": "var(--layout-prose-max)",
                     "wide": "var(--layout-wide-max)"},
        "screens": {k: f"{v}px" for k, v in layout["breakpoints"].items()},
    }
    js = ("// Generated by build_tokens.py from tokens.json. Do not edit by hand.\n"
          "// In tailwind.config: theme: { extend: require('./replica/design/tailwind.tokens.js') }\n"
          "module.exports = " + json.dumps(tw, indent=2, ensure_ascii=False) + ";\n")
    open(os.path.join(HERE, "tailwind.tokens.js"), "w", encoding="utf-8").write(js)
    print("wrote tokens.css and tailwind.tokens.js:", len(color), "colours,", len(typ), "type steps")


if __name__ == "__main__":
    main()
